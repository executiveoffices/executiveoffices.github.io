#!/usr/bin/env python3
"""Build cowboy-creek-mockup.html: a single self-contained file with the home page
(including the Cowboy Creek box) and the Cowboy Creek page, fonts/images/scripts inlined.
Run from the repo root:  python3 build-mockup.py
"""
import base64, pathlib, re

D = pathlib.Path(__file__).parent / "docs"
OUT = pathlib.Path(__file__).parent / "cowboy-creek-mockup.html"

def data_uri(rel, mime):
    return f"data:{mime};base64," + base64.b64encode((D / rel).read_bytes()).decode()

MIMES = {".webp": "image/webp", ".jpg": "image/jpeg", ".png": "image/png"}
images = {f"images/{p.name}": data_uri(f"images/{p.name}", MIMES[p.suffix])
          for p in (D / "images").iterdir() if p.suffix in MIMES}

def inline_images(s):
    for k in sorted(images, key=len, reverse=True):
        s = s.replace(k, images[k])
    return s

font_src = f"url('{data_uri('css/EBGaramond-Regular.woff2', 'font/woff2')}') format('woff2')"
FONT_RE = r"url\('EBGaramond-Regular\.woff2'\) format\('woff2'\),url\('EBGaramond-Regular\.woff'\) format\('woff'\)"
site_css = re.sub(FONT_RE, font_src, (D / "css/site.43e0f5.css").read_text())
cc_css = re.sub(FONT_RE, font_src, (D / "css/cowboy-creek.css").read_text())
leftover = [u for u in re.findall(r"url\([^)]*\)", site_css + cc_css) if not u.startswith("url('data:")]
assert not leftover, f"un-inlined url() refs: {leftover}"

# Home page body, with links rerouted to the in-file views.
idx = (D / "index.html").read_text(encoding="utf-8")
home = idx.split('<body id="b1">', 1)[1].split('<script>dpth="/"</script>', 1)[0].strip()
home = (home.replace('<a href="/" class="a1">', '<a href="#home" class="a1">')
            .replace('href="apply.html"', 'href="#home"')
            .replace('href="cowboy-creek.html"', 'href="#cowboy-creek"'))
home = inline_images(home)

# Ranch page body.
cc = (D / "cowboy-creek.html").read_text(encoding="utf-8")
ranch = cc.split('<body class="cc-page">', 1)[1].split('</body>', 1)[0].strip().replace('href="/"', 'href="#home"')

scripts = "\n".join(f"<script>\n{(D / 'js' / name).read_text()}\n</script>" for name in
                    ("jquery.7b1b8b.js", "woolite.7b1b8b.js", "executive-offices.43e0f5.js", "cowboy-creek-box.js", "home-fit.js"))
scripts = inline_images(scripts)

page = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Cowboy Creek mock-up · Executive Offices</title>
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="same-origin">
<!--
  Self-contained mock-up. Open this file directly in a browser; nothing else is needed.
  Home view: the Executive Offices home page with the Cowboy Creek box (fades in after 4 s).
  Click "Use & inquiries" in the box for the Cowboy Creek page; "Executive Offices" returns.
  Generated by build-mockup.py from the real files in docs/.
-->
<style>
{site_css}
</style>
<style>
{cc_css}
</style>
<style>
/* Mock-up shell: two views in one file. */
html,body{{background:#fff}}
body{{margin:0;overflow-x:hidden}}
.anim{{visibility:hidden}}
#view-home,#view-ranch{{display:none}}
body[data-view="home"] #view-home{{display:block}}
body[data-view="ranch"] #view-ranch{{display:block}}
</style>
</head>
<body data-view="home">

<div id="view-home">
{home}
</div>

<div id="view-ranch" class="cc-page">
{ranch}
</div>

<script>dpth="/"</script>
{scripts}
<script>
(function(){{
  function route(){{
    document.body.setAttribute('data-view', location.hash==='#cowboy-creek'?'ranch':'home');
    window.scrollTo(0,0);
    if (window.eoFit) window.eoFit();
  }}
  window.addEventListener('hashchange',route);
  route();
}})();
</script>
</body>
</html>
"""
OUT.write_text(page, encoding="utf-8")
print(f"wrote {OUT.name} ({OUT.stat().st_size // 1024} KB)")
